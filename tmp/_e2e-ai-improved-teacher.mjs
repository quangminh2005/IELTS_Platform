// Chụp mục "Bản nâng cấp của AI" ở trang chấm của thầy (DB LOCAL, JWT tự ký, không in token).
import { chromium } from "@playwright/test";
import { encode } from "next-auth/jwt";
import { PrismaClient } from "@prisma/client";
import fs from "fs";
const [port, outDir] = process.argv.slice(2);
const env = fs.readFileSync("E:/web_ielts/.env", "utf8");
const url = env.match(/^DATABASE_URL="?([^"\r\n]+)"?/m)[1];
const secret = env.match(/^NEXTAUTH_SECRET="?([^"\r\n]+)"?/m)[1];
const { assignmentId, attemptId } = JSON.parse(fs.readFileSync("E:/web_ielts/tmp/_e2e-ai-improved.json", "utf8"));
const p = new PrismaClient({ datasources: { db: { url } } });
const a = await p.assignment.findUnique({ where: { id: assignmentId }, select: { teacher: { select: { userId: true, user: { select: { email: true } } } } } });
await p.$disconnect();
const t = a.teacher;
const token = await encode({ secret, token: { sub: t.userId, id: t.userId, email: t.user.email, name: "Teacher", role: "teacher" } });
const browser = await chromium.launch({ channel: "chrome" });
const ctx = await browser.newContext({ viewport: { width: 1500, height: 1000 } });
await ctx.addCookies([{ name: "next-auth.session-token", value: token, domain: "localhost", path: "/", httpOnly: true }]);
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(`http://localhost:${port}/teacher/review/${attemptId}`, { waitUntil: "networkidle", timeout: 180000 });
const details = page.locator("details", { hasText: "Bản nâng cấp của AI" }).first();
console.log("details found:", await details.count());
await details.locator("summary").click();
await page.waitForTimeout(400);
await details.screenshot({ path: `${outDir}/5-teacher.png` });
console.log(errors.length ? errors.join("\n") : "no errors");
await browser.close();
